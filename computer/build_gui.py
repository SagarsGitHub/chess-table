"""Build the standalone GUI script from its model, view, and event modules.

The existing local HTTP server serves only /app.js. Keeping a self-contained
bundle also lets an already-running physical session reload its page safely.
Run ``python build_gui.py`` after editing the browser source files.
"""

from __future__ import annotations

from pathlib import Path
import re


STATIC = Path(__file__).parent / "chess_table_host" / "gui_static"
SOURCES = ("gui_model.js", "gui_view.js", "gui_entry.js")
IMPORT = re.compile(r'^import\s*\{[^}]*\}\s*from\s*"\./[^"]+";\s*', re.MULTILINE)
EXPORT = re.compile(r"^export (?=(?:const|function|class|let)\b)", re.MULTILINE)


def build() -> str:
    """Combine the ordered modules while removing only local module syntax."""
    parts = []
    for name in SOURCES:
        source = (STATIC / name).read_text(encoding="utf-8")
        source = IMPORT.sub("", source)
        source = EXPORT.sub("", source)
        source = source.replace('"use strict";\n', "", 1)
        if re.search(r"^(?:import|export)\s", source, re.MULTILINE):
            raise ValueError(f"unhandled module syntax in {name}")
        parts.append(f"// Source: {name}\n{source.strip()}\n")
    return (
        '"use strict";\n\n'
        '// Generated by computer/build_gui.py; edit gui_* source files.\n\n'
        + "\n".join(parts)
    )


if __name__ == "__main__":
    (STATIC / "app.js").write_text(build(), encoding="utf-8", newline="\n")
